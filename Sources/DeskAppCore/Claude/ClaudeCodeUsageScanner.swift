import Foundation

public struct DailyModelUsage: Sendable, Identifiable {
    public var id: String { "\(day.timeIntervalSince1970)|\(model)" }
    public let day: Date
    public let model: String
    public let tokens: TokenCounts
    /// API-equivalent USD; 0 for models without a known price.
    public let cost: Double
}

/// One Claude Code session (including its subagents) within the scan window.
public struct SessionSummary: Sendable, Identifiable {
    public let id: String
    /// Working directory the session ran in; `claude --resume` must be started from there.
    public let projectPath: String
    public let title: String?
    public let firstActivity: Date
    public let lastActivity: Date
    public let tokens: TokenCounts
    public let cost: Double
    /// Most used first.
    public let models: [String]

    public var projectName: String { (projectPath as NSString).lastPathComponent }
}

public struct CostSummary: Sendable {
    /// Sorted by day ascending.
    public let daily: [DailyModelUsage]
    public let unpricedModels: [String]
    /// Sorted by last activity, most recent first.
    public let sessions: [SessionSummary]

    public func cost(since start: Date) -> Double {
        daily.filter { $0.day >= start }.reduce(0) { $0 + $1.cost }
    }

    public func tokens(since start: Date) -> Int {
        daily.filter { $0.day >= start }.reduce(0) { $0 + $1.tokens.total }
    }
}

/// Aggregates token usage from Claude Code's session logs (`~/.claude/projects/**/*.jsonl`).
///
/// Logs can total several GB, so each file is read incrementally from the last processed offset
/// and the parsed entries are persisted to `cacheURL` between launches.
public actor ClaudeCodeUsageScanner {
    struct UsageEntry: Codable {
        let timestamp: Date
        let model: String
        let tokens: TokenCounts
        let sessionId: String?
        let cwd: String?
    }

    struct FileState: Codable {
        var offset: Int64 = 0
        /// Keyed by message id + request id. Streaming writes the same message several times;
        /// the last line wins.
        var entries: [String: UsageEntry] = [:]
        /// Session id -> title generated by Claude Code (`ai-title` lines).
        var titles: [String: String] = [:]
    }

    private struct CacheFile: Codable {
        static let currentVersion = 2
        let version: Int
        let files: [String: FileState]
    }

    private struct LogLine: Decodable {
        struct Message: Decodable {
            struct Usage: Decodable {
                struct CacheCreation: Decodable {
                    // convertFromSnakeCase capitalizes after digits: "ephemeral_1h_input_tokens" -> "ephemeral1HInputTokens".
                    let ephemeral5MInputTokens: Int?
                    let ephemeral1HInputTokens: Int?
                }
                let inputTokens: Int?
                let outputTokens: Int?
                let cacheCreationInputTokens: Int?
                let cacheReadInputTokens: Int?
                let cacheCreation: CacheCreation?
            }
            let id: String?
            let model: String?
            let usage: Usage?
        }
        let type: String?
        let timestamp: String?
        let requestId: String?
        let sessionId: String?
        let uuid: String?
        let cwd: String?
        let aiTitle: String?
        let message: Message?
    }

    private static let usageMarker = Data("\"usage\"".utf8)
    private static let assistantMarker = Data("\"assistant\"".utf8)
    private static let titleMarker = Data("\"type\":\"ai-title\"".utf8)
    private static let chunkSize = 8 << 20

    private let roots: [URL]
    private let cacheURL: URL?
    private let lookbackDays: Int
    private var files: [String: FileState] = [:]
    private var cacheLoaded = false
    private var dirty = false
    private let dateParser = ISO8601Parser()
    private let decoder: JSONDecoder = {
        let decoder = JSONDecoder()
        decoder.keyDecodingStrategy = .convertFromSnakeCase
        return decoder
    }()

    public init(roots: [URL] = ClaudeCodeUsageScanner.defaultRoots(), cacheURL: URL? = nil, lookbackDays: Int = 30) {
        self.roots = roots
        self.cacheURL = cacheURL
        self.lookbackDays = lookbackDays
    }

    public static func defaultRoots() -> [URL] {
        let home = FileManager.default.homeDirectoryForCurrentUser
        var roots = [
            home.appendingPathComponent(".claude/projects"),
            home.appendingPathComponent(".config/claude/projects"),
        ]
        if let configDir = ProcessInfo.processInfo.environment["CLAUDE_CONFIG_DIR"] {
            roots.insert(URL(fileURLWithPath: configDir).appendingPathComponent("projects"), at: 0)
        }
        return roots
    }

    public func scan(now: Date = Date()) -> CostSummary {
        loadCacheIfNeeded()
        let calendar = Calendar.current
        // `lookbackDays` calendar days including today, matching the "30 days" figure in the UI.
        let cutoff = calendar.date(byAdding: .day, value: -(lookbackDays - 1), to: calendar.startOfDay(for: now))!

        var seen = Set<String>()
        for url in logFiles() {
            guard let values = try? url.resourceValues(forKeys: [.fileSizeKey, .contentModificationDateKey]),
                  let size = values.fileSize,
                  let modified = values.contentModificationDate,
                  modified >= cutoff
            else { continue }
            let path = url.path
            seen.insert(path)
            var state = files[path] ?? FileState()
            if Int64(size) < state.offset {
                state = FileState() // truncated or rewritten
            }
            if Int64(size) > state.offset {
                readNewLines(url: url, state: &state)
                dirty = true
            }
            let before = state.entries.count
            state.entries = state.entries.filter { $0.value.timestamp >= cutoff }
            if state.entries.count != before { dirty = true }
            files[path] = state
        }
        if files.keys.contains(where: { !seen.contains($0) }) {
            files = files.filter { seen.contains($0.key) }
            dirty = true
        }
        saveCacheIfDirty()
        return summarize()
    }

    private func logFiles() -> [URL] {
        var urls: [URL] = []
        for root in roots {
            guard let enumerator = FileManager.default.enumerator(
                at: root,
                includingPropertiesForKeys: [.fileSizeKey, .contentModificationDateKey],
                options: [.skipsHiddenFiles]
            ) else { continue }
            for case let url as URL in enumerator where url.pathExtension == "jsonl" {
                urls.append(url)
            }
        }
        return urls
    }

    /// Reads complete lines appended since `state.offset`; a trailing partial line is left for the next scan.
    private func readNewLines(url: URL, state: inout FileState) {
        guard let handle = try? FileHandle(forReadingFrom: url) else { return }
        defer { try? handle.close() }
        do {
            try handle.seek(toOffset: UInt64(state.offset))
        } catch {
            return
        }
        var pending = Data()
        var reachedEnd = false
        while !reachedEnd {
            // FileHandle hands back autoreleased buffers; without a pool per chunk they pile up
            // until the scan ends (GBs on a first scan).
            autoreleasepool {
                guard let chunk = try? handle.read(upToCount: Self.chunkSize), !chunk.isEmpty else {
                    reachedEnd = true
                    return
                }
                pending.append(chunk)
                let consumed = consumeCompleteLines(pending, into: &state)
                state.offset += Int64(consumed)
                if consumed > 0 {
                    pending.removeSubrange(pending.startIndex..<pending.startIndex + consumed)
                }
            }
        }
    }

    /// Walks the buffer's bytes directly and only materializes lines that mention usage, so lines of
    /// hundreds of MB (tool results with images) cost no copies. Returns the number of bytes consumed.
    private func consumeCompleteLines(_ buffer: Data, into state: inout FileState) -> Int {
        var candidates: [Data] = []
        let consumed = buffer.withUnsafeBytes { (raw: UnsafeRawBufferPointer) -> Int in
            guard let base = raw.baseAddress else { return 0 }
            var start = 0
            while start < raw.count,
                  let hit = memchr(base + start, Int32(UInt8(ascii: "\n")), raw.count - start) {
                let end = base.distance(to: UnsafeRawPointer(hit))
                let line = UnsafeRawBufferPointer(rebasing: raw[start..<end])
                if (Self.contains(line, Self.usageMarker) && Self.contains(line, Self.assistantMarker))
                    || Self.contains(line, Self.titleMarker) {
                    candidates.append(Data(line))
                }
                start = end + 1
            }
            return start
        }
        for line in candidates {
            ingest(line: line, into: &state)
        }
        return consumed
    }

    private static func contains(_ haystack: UnsafeRawBufferPointer, _ needle: Data) -> Bool {
        guard let base = haystack.baseAddress else { return false }
        return needle.withUnsafeBytes { memmem(base, haystack.count, $0.baseAddress, needle.count) != nil }
    }

    private func ingest(line: Data, into state: inout FileState) {
        guard let record = try? decoder.decode(LogLine.self, from: line) else { return }
        if record.type == "ai-title" {
            if let sessionId = record.sessionId, let title = record.aiTitle, title != "no-conversation-content" {
                state.titles[sessionId] = title
            }
            return
        }
        guard record.type == "assistant",
              let message = record.message,
              let usage = message.usage,
              let model = message.model,
              model != "<synthetic>",
              let timestamp = record.timestamp.flatMap(dateParser.parse)
        else { return }

        let cacheCreation = usage.cacheCreationInputTokens ?? 0
        let write1h = usage.cacheCreation?.ephemeral1HInputTokens ?? 0
        let tokens = TokenCounts(
            input: usage.inputTokens ?? 0,
            output: usage.outputTokens ?? 0,
            // Older logs only have the total; treat it as the default 5-minute cache.
            cacheWrite5m: usage.cacheCreation?.ephemeral5MInputTokens ?? (cacheCreation - write1h),
            cacheWrite1h: write1h,
            cacheRead: usage.cacheReadInputTokens ?? 0
        )
        let key = "\(message.id ?? record.uuid ?? "")|\(record.requestId ?? record.sessionId ?? "")"
        state.entries[key] = UsageEntry(
            timestamp: timestamp,
            model: ModelPricing.normalize(model),
            tokens: tokens,
            sessionId: record.sessionId,
            cwd: record.cwd
        )
    }

    private func summarize() -> CostSummary {
        struct Key: Hashable {
            let day: Date
            let model: String
        }
        // The same message can appear in more than one file (e.g. resumed sessions), so dedupe globally.
        var unique: [String: UsageEntry] = [:]
        for state in files.values {
            unique.merge(state.entries) { _, new in new }
        }

        let calendar = Calendar.current
        var tokensByKey: [Key: TokenCounts] = [:]
        var costByKey: [Key: Double] = [:]
        var unpriced = Set<String>()
        for entry in unique.values {
            let key = Key(day: calendar.startOfDay(for: entry.timestamp), model: entry.model)
            tokensByKey[key, default: TokenCounts()] += entry.tokens
            if let cost = ModelPricing.cost(model: entry.model, tokens: entry.tokens) {
                costByKey[key, default: 0] += cost
            } else {
                unpriced.insert(entry.model)
            }
        }
        let daily = tokensByKey
            .map { DailyModelUsage(day: $0.key.day, model: $0.key.model, tokens: $0.value, cost: costByKey[$0.key] ?? 0) }
            .sorted { ($0.day, $0.model) < ($1.day, $1.model) }
        return CostSummary(daily: daily, unpricedModels: unpriced.sorted(), sessions: summarizeSessions(unique.values))
    }

    private func summarizeSessions(_ entries: Dictionary<String, UsageEntry>.Values) -> [SessionSummary] {
        var titles: [String: String] = [:]
        for state in files.values {
            titles.merge(state.titles) { _, new in new }
        }
        let bySession = Dictionary(grouping: entries.filter { $0.sessionId != nil }, by: { $0.sessionId! })
        return bySession.compactMap { sessionId, entries -> SessionSummary? in
            let sorted = entries.sorted { $0.timestamp < $1.timestamp }
            // Subagent lines share the parent's session id; the latest cwd is where to resume.
            guard let first = sorted.first, let last = sorted.last,
                  let cwd = sorted.last(where: { $0.cwd != nil })?.cwd
            else { return nil }
            var tokens = TokenCounts()
            var cost = 0.0
            var tokensByModel: [String: Int] = [:]
            for entry in sorted {
                tokens += entry.tokens
                cost += ModelPricing.cost(model: entry.model, tokens: entry.tokens) ?? 0
                tokensByModel[entry.model, default: 0] += entry.tokens.total
            }
            return SessionSummary(
                id: sessionId,
                projectPath: cwd,
                title: titles[sessionId],
                firstActivity: first.timestamp,
                lastActivity: last.timestamp,
                tokens: tokens,
                cost: cost,
                models: tokensByModel.sorted { $0.value > $1.value }.map(\.key)
            )
        }
        .sorted { $0.lastActivity > $1.lastActivity }
    }

    private func loadCacheIfNeeded() {
        guard !cacheLoaded else { return }
        cacheLoaded = true
        guard let cacheURL,
              let data = try? Data(contentsOf: cacheURL),
              let cache = try? JSONDecoder().decode(CacheFile.self, from: data),
              cache.version == CacheFile.currentVersion
        else { return }
        files = cache.files
    }

    private func saveCacheIfDirty() {
        guard dirty, let cacheURL else { return }
        dirty = false
        do {
            try FileManager.default.createDirectory(at: cacheURL.deletingLastPathComponent(), withIntermediateDirectories: true)
            let data = try JSONEncoder().encode(CacheFile(version: CacheFile.currentVersion, files: files))
            try data.write(to: cacheURL, options: .atomic)
        } catch {
            // The cache is only an optimization; the next launch rescans.
        }
    }
}
